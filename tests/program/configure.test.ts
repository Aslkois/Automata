const compiles = (code: string) => {
  const p = parseBrain(code);
  expect(p.diagnostics).toEqual([]);
  const c = compileBrain(p.ir!, 'g', 'g');
  expect(c.errors).toEqual([]);
  return c.program;
};

describe('configure: generation', () => {
  it('every doctrine generates a brain that compiles and runs on every starter’s hardware', () => {
    for (const d of DEFAULT_DESIGNS) {
      for (const doc of DOCTRINES) {
        const program = compiles(generateCode(d, defaultConfig(doc.id)));
        if (doc.id !== 'balanced' && doc.id !== 'adaptive') continue;
        const sim = new Simulation({ seed: 3, arena: defaultArena(), mode: 'duel', timeLimit: 0, decisionHz: 10, drones: [{ design: d, program, team: 0 }, { design: PICKET, program: compiles(generateCode(PICKET, defaultConfig())), team: 1 }] });
        sim.run(8);
        for (const c of sim.controllers.values()) expect(c.lastError, `${d.name} ${doc.id}`).toBeNull();
      }
    }
  }, 120_000);

  it('only generates behaviour for installed equipment', () => {
    const picket = generateCode(PICKET, defaultConfig());
    expect(picket).not.toMatch(/function coilgun|function missiles|function rockets|function pointDefense|raiseShield/);
    expect(generateCode(LONGBOW, defaultConfig())).toMatch(/function coilgun/);
    expect(generateCode(TALON, defaultConfig())).toMatch(/function missiles/);
    expect(generateCode(HORNET, defaultConfig())).toMatch(/function rockets/);
    expect(generateCode(WARDEN, defaultConfig())).toMatch(/function pointDefense/);
    expect(generateCode(JUGGERNAUT, defaultConfig())).toMatch(/raiseShield/);
    // the hardware it refers to is the drone's own
    for (const d of DEFAULT_DESIGNS) {
      const code = generateCode(d, defaultConfig());
      for (const w of analyzeHardware(d).weapons) expect(code, `${d.name} ${w.id}`).toContain(`"${w.id}"`);
    }
  });

  it('the generated program is readable: commented settings and named modules', () => {
    const code = generateCode(PARAGON, defaultConfig('adaptive'));
    expect(code).toMatch(/^\/\/ Paragon — brain generated by Configure/);
    expect(code).toMatch(/const RANGE_MIN = \d+;\s+\/\/ closer than this/);
    for (const fn of ['function chooseTarget', 'function decide', 'function move', 'function fireControl', 'function update']) expect(code).toContain(fn);
    // decisions are logged so the debugger shows the brain's state
    expect(code).toMatch(/drone\.log\("mode: "/);
  });

  it('primary choices each change the program', () => {
    const base = generateCode(PARAGON, defaultConfig());
    const vary = (c: Partial<BrainConfig>) => generateCode(PARAGON, { ...defaultConfig(), ...c });
    for (const d of DOCTRINES) if (d.id !== 'balanced') expect(generateCode(PARAGON, defaultConfig(d.id)), d.id).not.toBe(base);
    for (const range of ['close', 'medium', 'long', 'custom'] as const) expect(vary({ range, customRange: [200, 400] }), range).not.toBe(base);
    for (const target of ['nearest', 'threat', 'vulnerable', 'fastest', 'heaviest', 'adaptive'] as const) expect(vary({ target }), target).not.toBe(base);
    for (const defense of ['survival', 'offense', 'intercept', 'evasive', 'armor'] as const) expect(vary({ defense }), defense).not.toBe(base);
    for (const movement of ['hold', 'advance', 'pursue', 'kite', 'flank', 'patrol', 'adaptive'] as const) expect(vary({ movement }), movement).not.toBe(base);
  });

  it('every advanced setting changes the program on hardware it applies to', () => {
    const changes: { [K in keyof AdvancedConfig]: [AdvancedConfig[K], DroneDesign?, Partial<BrainConfig>?] } = {
      rangeMin: [150],
      rangeMax: [500],
      pursuit: [0.1],
      retreatAt: [0.6],
      orbit: ['cw'],
      flank: ['left', PARAGON, { movement: 'flank' }],
      cover: [true],
      speed: [0.6],
      stuckRecovery: [false],
      search: ['patrol'],
      memory: [3],
      discipline: ['free'],
      aimTolerance: [8],
      lead: [false],
      burst: [true],
      reloadDisengage: [true],
      coilgunBrace: [false, LONGBOW],
      rocketSalvo: ['free', HORNET],
      missileConservation: [false, TALON],
      interceptorReserve: [6, WARDEN],
      weights: [{ distance: 2, threat: 0, mobility: 1, freshness: 1, armor: 1 }],
      power: ['weapons'],
      heatLimit: [70],
      ammoConserveBelow: [0.5],
      emergencyPower: [false, JUGGERNAUT],
      incoming: ['evade'],
      shieldFacing: ['target', JUGGERNAUT],
      sensorLoss: ['retreat'],
      weaponLoss: ['retreat'],
      fightImmobilized: [false],
      adaptRange: [false],
      adaptPropulsion: [false],
      avoidRepeats: [false],
      readEnemy: [false],
    };
    const keys = Object.keys(defaultConfig().advanced) as (keyof AdvancedConfig)[];
    expect(Object.keys(changes).sort()).toEqual([...keys].sort());
    const dead: string[] = [];
    for (const k of keys) {
      // settings that belong to one manoeuvre are tested with that manoeuvre chosen
      const [v, d = PARAGON, extra = {}] = changes[k] as [unknown, DroneDesign?, Partial<BrainConfig>?];
      const base = { ...defaultConfig('adaptive'), ...extra };
      const before = generateCode(d, base);
      const after = generateCode(d, { ...base, advanced: { ...base.advanced, [k]: v } });
      if (before === after) dead.push(k);
      else compiles(after);
    }
    expect(dead).toEqual([]);
  }, 60_000);

  it('stored settings are validated: unknown values fall back, numbers are clamped', () => {
    const c = parseConfig({ doctrine: 'reckless', range: 'far', target: 'nearest', advanced: { speed: 9, heatLimit: -5, memory: 'x', orbit: 'cw', weights: { distance: 99 } } });
    expect(c.doctrine).toBe('balanced');
    expect(c.range).toBe('auto');
    expect(c.target).toBe('nearest');
    expect(c.advanced.speed).toBe(1);
    expect(c.advanced.heatLimit).toBe(50);
    expect(c.advanced.memory).toBe(defaultConfig().advanced.memory);
    expect(c.advanced.orbit).toBe('cw');
    expect(c.advanced.weights.distance).toBe(2);
    expect(parseConfig(null)).toEqual(defaultConfig());
  });

  it('a first configuration follows the weapons', () => {
    expect(initialConfig(LONGBOW).doctrine).toBe('precision');
    expect(initialConfig(TALON).doctrine).toBe('precision');
    expect(initialConfig(WARDEN).doctrine).toBe('interception');
    expect(initialConfig(PICKET).doctrine).toBe('balanced');
  });

  it('the explanation is derived from the same plan as the program', () => {
    const ex = explain(LONGBOW, defaultConfig('precision'));
    const code = generateCode(LONGBOW, defaultConfig('precision'));
    expect(code).toContain(`const RANGE_MIN = ${ex.plan.band[0]};`);
    expect(code).toContain(`const RANGE_MAX = ${ex.plan.band[1]};`);
    expect(ex.behaviour.join(' ')).toMatch(/Coilgun/);
    expect(ex.omitted.join(' ')).toMatch(/No missiles/);
    expect(explain(PICKET, defaultConfig()).omitted.join(' ')).toMatch(/No coilgun/);
  });
});

describe('configure: the brain and its settings', () => {
  const configured = (d: DroneDesign = PICKET, c = defaultConfig()) => applyConfig(newBrain('b', d.id, STARTER_CODE, 'configure'), d, c);

  it('a generated brain is synced; a hand-written one has no settings', () => {
    expect(configStatus(newBrain('b', PICKET.id), PICKET)).toBe('none');
    const b = configured();
    expect(configStatus(b, PICKET)).toBe('synced');
    expect(b.view).toBe('configure');
    expect(b.config!.data).toEqual(defaultConfig());
  });

  it('an edit in another editor marks the brain customised; settings are then stored, not applied', () => {
    const b = configured();
    const doc = codeDocFor(b.ir);
    const r = applyEdit(b, 'code', { ...doc, text: doc.text.replace('function update() {', 'function update() {\n  drone.log("mine");') });
    expect(r.ok && r.changed).toBe(true);
    expect(configStatus(r.brain, PICKET)).toBe('customized');
    const stored = storeSettings(r.brain, defaultConfig('aggressive'));
    expect(stored.ir).toEqual(r.brain.ir);
    expect(stored.config!.data.doctrine).toBe('aggressive');
    expect(configStatus(stored, PICKET)).toBe('customized');
  });

  it('switching editors does not change the program or its sync state', () => {
    const b = configured();
    for (const v of ['blocks', 'nodes', 'code', 'configure'] as const) expect(configStatus({ ...b, view: v }, PICKET)).toBe('synced');
  });

  it('a hardware change regenerates a synced brain and leaves a customised one alone', () => {
    const b = configured();
    const changed: DroneDesign = cloneDesign(PICKET);
    delete changed.sections.front.slots.H2;
    expect(configStatus(b, changed)).toBe('hardware');
    const refreshed = refreshForHardware(b, changed);
    expect(configStatus(refreshed, changed)).toBe('synced');
    expect(codeDocFor(refreshed.ir).text).not.toContain('"F.H2"');
    const doc = codeDocFor(b.ir);
    const custom = applyEdit(b, 'code', { ...doc, text: doc.text.replace('function update() {', 'function update() {\n  drone.log("mine");') }).brain;
    expect(refreshForHardware(custom, changed)).toBe(custom);
  });

  it('settings survive save/load, duplication (fresh node ids) and export/import', () => {
    const b = configured(PARAGON, defaultConfig('harassment'));
    const loaded = validateBrain(JSON.parse(JSON.stringify(b)));
    expect(loaded.config).toEqual(b.config);
    expect(configStatus(loaded, PARAGON)).toBe('synced');
    const dup = { ...loaded, id: 'b2', ir: { body: freshIds(loaded.ir.body) } };
    expect(configStatus(dup, PARAGON)).toBe('synced');
    // an old brain with no settings stays valid
    expect(validateBrain(JSON.parse(JSON.stringify({ ...b, config: undefined }))).config).toBeUndefined();
    // a damaged settings block is repaired, not fatal
    expect(validateBrain(JSON.parse(JSON.stringify({ ...b, config: { ...b.config, data: { doctrine: 42 } } }))).config!.data.doctrine).toBe('balanced');
  });

  it('generate() records what it generated', () => {
    const g = generate(TALON, defaultConfig('precision'));
    expect(g.meta.hardware).toBe(analyzeHardware(TALON).key);
    expect(irFromCode(g.code)).toBeTruthy();
  });
});

describe('configure: the library', () => {
  it('generating over a hand-written or customised brain keeps the old program recoverable', () => {
    const d = library.createDesign('Configure probe');
    const before = library.get().recovered.length;
    const r1 = library.configureBrain(d.id, defaultConfig('defensive'));
    expect(r1.recovered).toBe(true);
    expect(library.get().recovered.length).toBe(before + 1);
    expect(configStatus(library.brainFor(d.id)!, d)).toBe('synced');
    // synced: regenerating does not pile up copies
    const r2 = library.configureBrain(d.id, defaultConfig('aggressive'));
    expect(r2.recovered).toBe(false);
    expect(library.get().recovered.length).toBe(before + 1);
    // customised: settings are stored without touching the program
    const b = library.brainFor(d.id)!;
    const doc = codeDocFor(b.ir);
    library.editBrain(d.id, 'code', { ...doc, text: doc.text.replace('function update() {', 'function update() {\n  drone.log("mine");') });
    const edited = library.brainFor(d.id)!;
    library.storeConfigSettings(d.id, defaultConfig('precision'));
    expect(library.brainFor(d.id)!.ir).toEqual(edited.ir);
    expect(library.brainFor(d.id)!.config!.data.doctrine).toBe('precision');
    // a hardware change follows a synced brain only
    library.configureBrain(d.id, defaultConfig('balanced'));
    const design = library.get().designs.find((x) => x.id === d.id)!;
    library.upsertDesign({ ...design, sections: { ...design.sections, front: { ...design.sections.front, slots: { ...design.sections.front.slots, H1: { component: 'mg', rotation: 0 } } } } });
    expect(configStatus(library.brainFor(d.id)!, library.get().designs.find((x) => x.id === d.id)!)).toBe('synced');
    expect(codeDocFor(library.brainFor(d.id)!.ir).text).toContain('"F.H1"');
    library.deleteDesign(d.id);
  });

  it('duplicate, export and import keep the settings', () => {
    const d = library.createDesign('Configure export probe');
    library.configureBrain(d.id, defaultConfig('area'));
    const dup = library.duplicateDesign(d.id)!;
    expect(configStatus(library.brainFor(dup.id)!, dup)).toBe('synced');
    const bundle = JSON.parse(JSON.stringify(library.exportBundle(d.id)));
    const imported = library.importBundle(bundle);
    expect(library.brainFor(imported.id)!.config!.data.doctrine).toBe('area');
    expect(configStatus(library.brainFor(imported.id)!, imported)).toBe('synced');
    for (const id of [d.id, dup.id, imported.id]) library.deleteDesign(id);
  });
});

describe('debugger: brain state', () => {
  it('reads the newest logged state and recent activity from the decision history, for generated and starter brains', async () => {
    const { brainState } = await import('../../src/ui/program/brainState');
    const { DEFAULT_BRAINS } = await import('../../src/data/defaults');
    for (const [d, code] of [
      [LONGBOW, generateCode(LONGBOW, defaultConfig('precision'))],
      [PARAGON, DEFAULT_BRAINS.find((b) => b.designId === PARAGON.id)!.code],
      [SOVEREIGN, DEFAULT_BRAINS.find((b) => b.designId === SOVEREIGN.id)!.code],
    ] as const) {
      const sim = new Simulation({ seed: 2, arena: defaultArena(), mode: 'duel', timeLimit: 0, decisionHz: 10, drones: [{ design: d, program: compiles(code), team: 0 }, { design: PICKET, program: compiles(generateCode(PICKET, defaultConfig())), team: 1 }] });
      sim.run(12);
      const ctrl = sim.controllers.get(sim.drones[0].id)!;
      const s = brainState(ctrl.history, sim.time);
      expect(s, d.name).not.toBeNull();
      expect(s!.state.length, d.name).toBeGreaterThan(2);
      expect(s!.loc.kind).toBe('line');
    }
    // Sovereign reports its plan from its first decision, before it has seen anything
    const sim = new Simulation({ seed: 1, arena: defaultArena(), mode: 'duel', timeLimit: 0, decisionHz: 10, drones: [{ design: SOVEREIGN, program: compiles(DEFAULT_BRAINS.find((b) => b.designId === SOVEREIGN.id)!.code), team: 0 }, { design: PICKET, program: compiles(generateCode(PICKET, defaultConfig())), team: 1 }] });
    sim.run(0.3);
    expect(brainState(sim.controllers.get(sim.drones[0].id)!.history, sim.time)?.state).toBe('search');
  }, 30_000);
});
